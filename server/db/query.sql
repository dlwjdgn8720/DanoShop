/** qna 테이블 **/
CREATE TABLE IF NOT EXISTS `qna` (
  `qid` int NOT NULL AUTO_INCREMENT,
  `post_num` int NOT NULL,
  `category` varchar(50) not null,
  `title` varchar(255) NOT NULL,
  `content` text DEFAULT NULL,
  `writer` varchar(50) NOT NULL,
  `views` int default 0,
  `is_secret` tinyint DEFAULT 1,
  `is_reply` tinyint DEFAULT 0,
  `group_id` int DEFAULT NULL,
  `cdate` datetime NOT NULL,
  `udate` datetime DEFAULT NULL,
  `mid` varchar(50) NOT NULL,
  `pid` int NOT NULL,
  PRIMARY KEY (`qid`),
  KEY `fk_member_id` (`mid`),
  KEY `fk_product_pid` (`pid`),
  CONSTRAINT `fk_member_id` FOREIGN KEY (`mid`) REFERENCES `member` (`mid`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_product_pid` FOREIGN KEY (`pid`) REFERENCES `product` (`pid`) ON DELETE CASCADE ON UPDATE CASCADE);
  

