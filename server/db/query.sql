/** 회원 테이블 */
CREATE TABLE IF NOT EXISTS `member` (
  `mid` varchar(50) NOT NULL,
  `pwd` varchar(100) NOT NULL,
  `name` varchar(20) NOT NULL,
  `phone` char(13) DEFAULT NULL,
  `address` varchar(100) not null,
  `email` varchar(50) NOT NULL,
  `mdate` date DEFAULT NULL,
  `role` varchar(20) DEFAULT 'USER',
  PRIMARY KEY (`mid`)
);

/** 상품 테이블 */
CREATE TABLE IF NOT EXISTS `product` (
    `pid`         	INT          	NOT NULL PRIMARY KEY,
    `image`       	VARCHAR(100),
    `sticker`     	VARCHAR(30)		DEFAULT NULL,
    `name`        	VARCHAR(100),
    `composition` 	VARCHAR(50)		DEFAULT NULL,
    `price`       	VARCHAR(20),
    `sale_price`  	VARCHAR(20)		DEFAULT NULL,
    `product_imgb` 	VARCHAR(100),
    `product_imgs` 	VARCHAR(100),
    `image_set`   	JSON,
    `summary_info` 	VARCHAR(100),
    `discount`    	VARCHAR(20)		DEFAULT NULL,
    `info_name`		VARCHAR(100),
    `keep`			VARCHAR(50),
    `volume`		VARCHAR(100)
);

/** 상품 옵션 테이블 */
CREATE TABLE IF NOT EXISTS `product_option` ( 
    `poid`       	INT  NOT NULL AUTO_INCREMENT PRIMARY KEY,
    `pid`        	INT,
    `option`    	VARCHAR(100),
    `price`      	VARCHAR(20),
    `sale_price` 	VARCHAR(20)		DEFAULT NULL,
    FOREIGN KEY (pid) REFERENCES product(pid)
);

-- 리뷰(글씨) 테이블
CREATE TABLE IF NOT EXISTS review (
    rid INT AUTO_INCREMENT PRIMARY KEY,
    pid INT,
    tag_new VARCHAR(10) DEFAULT NULL,
    tag_repurchase VARCHAR(20) DEFAULT NULL,
    `date` DATE DEFAULT NULL,
    message VARCHAR(200),
    user_name VARCHAR(10),
    `option` VARCHAR(100),
    
    FOREIGN KEY (pid) REFERENCES product(pid)
);

-- 리뷰(이미지) 테이블
CREATE TABLE IF NOT EXISTS media_review (
    mrid INT AUTO_INCREMENT PRIMARY KEY,
    pid INT,
    media VARCHAR(100),
    
    FOREIGN KEY (pid) REFERENCES product(pid)
);

-- 카트(장바구니) 테이블
DROP VIEW IF EXISTS `view_cartlist`;
DROP TABLE IF EXISTS `cart`;

-- 공백이나 유령 문자 없이 완전히 깔끔한 텍스트로 cart 테이블을 재생성합니다.
CREATE TABLE `cart` (
  `pid` INT NOT NULL,
  `mid` VARCHAR(50) NOT NULL,
  `cid` INT PRIMARY KEY AUTO_INCREMENT,
  `qty` INT NOT NULL DEFAULT 1,
  `total_qty` INT DEFAULT 0,
  `total_price` INT DEFAULT 0,
  `total_sale` INT DEFAULT 0,
  `cdate` DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (`pid`) REFERENCES `product`(`pid`),
  FOREIGN KEY (`mid`) REFERENCES `member`(`mid`)
);

-- view cartlist 테이블
-- 기존 뷰 삭제 후, 재생성
DROP VIEW IF EXISTS `view_cartlist`;

CREATE VIEW view_cartlist AS
SELECT
    m.mid AS mid,
    m.name AS mname,
    m.phone AS phone,
    m.email AS email,

    p.pid AS pid,
    p.name AS name,
    p.summary_info AS info,
    p.image AS image,
    p.price AS price,

    po.option AS size,

    c.qty AS qty,
    c.cid AS cid,
    c.poid AS poid,

    SUM(
        c.qty * CAST(REPLACE(p.price, ',', '') AS UNSIGNED)
    ) OVER (
        PARTITION BY m.mid
    ) AS total_price

FROM member m
JOIN cart c
    ON m.mid = c.mid
JOIN product p
    ON p.pid = c.pid
LEFT JOIN product_option po
    ON po.poid = c.poid;

